// The class belongs to the Scene namespace
namespace BimGo.Scene
{
    /// <summary>
    /// Round X-B3: a traced silhouette (a drawing turned into vector rings by <c>tools/entourage/trace.py</c>): rings
    /// [u, v, …] in units of its height (the ground at v = 0, u = 0 its middle), filled even-odd so inner rings are holes
    /// (the gap under an arm, between legs). Drawn at 512 px like the procedural pictures, so it is tiny in the code,
    /// tintable and the same on every machine.
    /// </summary>
    /// <param name="Key">The built-in it replaces ("person-man") or a new key ("person-sketch-1").</param>
    /// <param name="Name">Shown in the panel.</param>
    /// <param name="Category">See <see cref="EntourageCategories"/>.</param>
    /// <param name="Height">Planting height (m).</param>
    /// <param name="Width">Its width in units of its height (the canvas fits the larger).</param>
    /// <param name="Smooth">Chaikin passes when drawn (0–3: rounds the simplified outline).</param>
    /// <param name="Rings">The outline rings.</param>
    /// <param name="Credit">Who drew it (THIRD-PARTY-NOTICES / README list it too).</param>
    public sealed record EntourageShape(string Key, string Name, string Category, float Height, double Width, int Smooth, double[][] Rings, string Credit);

    /// <summary>
    /// Round X-B3: the traced silhouettes shipped with BimGo. Empty until Gavin's drawings arrive: each one either
    /// replaces a procedural built-in (same key) or adds a type. Only drawings that may be redistributed under MIT-0 /
    /// CC0 go here (Gavin's own, credited; never a third-party pack).
    /// </summary>
    public static class EntourageShapes
    {
        /// <summary>The traced silhouettes (generated by tools/entourage/trace.py; paste its output here).</summary>
        public static readonly EntourageShape[] ALL = Array.Empty<EntourageShape>();

        /// <summary>The traced silhouette with a key, or null.</summary>
        public static EntourageShape Find(string key)
        {
            foreach (EntourageShape shape in ALL) { if (shape.Key == key) { return shape; } }
            return null;
        }

        /// <summary>
        /// The fill colour of a traced silhouette in the "own colours" look (a darkened category colour: it has no
        /// colours of its own). The silhouette look tints it like any other picture.
        /// </summary>
        public static uint FillOf(string category)
        {
            uint rgb = EntourageCategories.DEFAULT_COLOURS[EntourageCategories.IndexOf(category)];
            uint r = (rgb >> 16) & 255, g = (rgb >> 8) & 255, b = rgb & 255;
            return ((r * 3 / 5) << 16) | ((g * 3 / 5) << 8) | (b * 3 / 5);
        }
    }
}
